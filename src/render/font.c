#define GLYPH_W 5
#define GLYPH_H 7
#define GLYPH_ADVANCE 6

static const unsigned char	*glyph(char c)
{
	int	u;

	u = toupper((unsigned char)c);
	if (u < 32 || u > 'Z')
		u = '?';
	return (g_font[u - 32]);
}

int	text_width(const char *s, int scale)
{
	int	len;

	len = (int)strlen(s);
	if (len == 0)
		return (0);
	return ((len * GLYPH_ADVANCE - 1) * scale);
}

/* Draws each glyph row as horizontal runs to keep the rect count low. */
static void	draw_glyph(t_platform *p, const unsigned char *rows, int x, int y,
		int scale, uint32_t rgba)
{
	int	r;
	int	c;
	int	run;

	r = 0;
	while (r < GLYPH_H)
	{
		c = 0;
		while (c < GLYPH_W)
		{
			run = 0;
			while (c + run < GLYPH_W
				&& (rows[r] >> (GLYPH_W - 1 - (c + run)) & 1))
				run++;
			if (run > 0)
				platform_fill_rect(p, x + c * scale, y + r * scale,
					run * scale, scale, rgba);
			c += run + 1;
		}
		r++;
	}
}

void	draw_text(t_platform *p, const char *s, const int pos[2], int scale,
		uint32_t rgba)
{
	int	x;

	x = pos[0];
	while (*s)
	{
		draw_glyph(p, glyph(*s), x, pos[1], scale, rgba);
		x += GLYPH_ADVANCE * scale;
		s++;
	}
}

void	draw_text_centered(t_platform *p, const char *s, const int pos[2],
		int scale, uint32_t rgba)
{
	draw_text(p, s, (const int [2]){pos[0] - text_width(s, scale) / 2,
		pos[1]}, scale, rgba);
}
